#!/usr/bin/env python3
"""Linux replacement for AMD's FidelityFX_SC.exe (GL target): compiles every FSR 2 pass permutation
to SPIR-V with glslangValidator and writes the <pass>_permutations.h headers that the GL backend
(ffx_fsr2_shaders_gl.cpp) includes.  Usage: gen_fsr2_shaders.py <ffx-fsr2-api/shaders dir> <out dir>"""
import sys, os, re, struct, subprocess, hashlib, concurrent.futures as cf

SRC, OUT = os.path.abspath(sys.argv[1]), os.path.abspath(sys.argv[2])
os.makedirs(OUT, exist_ok=True)
PASSES = ["tcr_autogen", "autogen_reactive", "accumulate", "compute_luminance_pyramid",
          "depth_clip", "lock", "reconstruct_previous_depth", "rcas"]
# key bit order = field order in the generated PermutationKey union
OPTS = ["FFX_FSR2_OPTION_REPROJECT_USE_LANCZOS_TYPE", "FFX_FSR2_OPTION_HDR_COLOR_INPUT",
        "FFX_FSR2_OPTION_LOW_RESOLUTION_MOTION_VECTORS", "FFX_FSR2_OPTION_JITTERED_MOTION_VECTORS",
        "FFX_FSR2_OPTION_INVERTED_DEPTH", "FFX_FSR2_OPTION_APPLY_SHARPENING", "FFX_HALF"]
BASE = ["glslangValidator", "-G", "--target-env", "opengl", "--target-env", "spirv1.3", "-S", "comp", "-e", "main", "-Os", "--amb", "--stb", "comp", "8", "--ssb", "comp", "8", "--sib", "comp", "0", "--suavb", "comp", "0",
        "-DFFX_GPU=1", "-DFFX_GLSL=1", "-q"]

def compile_one(pas, idx):
    # options are tested with #ifdef / #if defined, so only define the ones that are on; FFX_HALF is #if
    defs = [f"-D{o}=1" for b, o in enumerate(OPTS) if (idx >> b) & 1 and o != "FFX_HALF"]
    defs.append(f"-DFFX_HALF={(idx >> OPTS.index('FFX_HALF')) & 1}")
    spv = os.path.join(OUT, f"tmp_{pas}_{idx}.spv")
    r = subprocess.run(BASE + defs + ["-o", spv, os.path.join(SRC, f"ffx_fsr2_{pas}_pass.glsl2")],
                       capture_output=True, text=True, cwd=SRC)
    if r.returncode or not os.path.exists(spv):
        if idx in (0, 64): sys.stderr.write(f"{pas} {idx}: " + "\n".join(l for l in r.stdout.splitlines() if "ERROR" in l)[:600] + "\n")
        return pas, idx, None
    data = open(spv, "rb").read(); os.remove(spv)
    # active resources from glslang's reflection: "name: offset -1, type XXXX, ..., binding N"
    imgs, smps, ubos = [], [], []
    sect = ""
    for line in r.stdout.splitlines():
        if line.endswith("reflection:"): sect = line; continue
        m = re.match(r"(\w+): offset -?\d+, type ([0-9a-f]+), .*binding (-?\d+)", line)
        if not m: continue
        name, ty, bnd = m.group(1), int(m.group(2), 16), int(m.group(3))
        if sect.startswith("Uniform block"):
            ubos.append((name, bnd))
        elif sect.startswith("Uniform reflection") and bnd >= 0 and "." not in name:
            (imgs if 0x904C <= ty <= 0x906C else smps).append((name, bnd))
    # GL image units are their own namespace and NVIDIA has only 8: renumber storage images 0..n-1
    # (glslang's auto-map numbered them after the textures) by patching their SPIR-V Binding decorations.
    imgs.sort(key=lambda x: x[1])
    newb = {n: i for i, (n, _) in enumerate(imgs)}
    words = list(struct.unpack(f"<{len(data)//4}I", data))
    names, k = {}, 5
    while k < len(words):
        op, wc = words[k] & 0xffff, words[k] >> 16
        if op == 5:   # OpName
            raw = struct.pack(f"<{wc-2}I", *words[k+2:k+wc]); names[words[k+1]] = raw.split(b"\0")[0].decode()
        elif op == 71 and words[k+2] == 33 and names.get(words[k+1]) in newb:   # OpDecorate id Binding n
            words[k+3] = newb[names[words[k+1]]]
        k += wc
    data = struct.pack(f"<{len(words)}I", *words)
    imgs = [(n, newb[n]) for n, _ in imgs]
    # blocks: reflection gives the type name (cbFSR2_t); the backend matches instance names (cbFSR2)
    ubos = [(n[:-2] if n.endswith("_t") else n, b) for n, b in ubos]
    return pas, idx, (data, sorted(imgs, key=lambda x: x[1]), sorted(smps, key=lambda x: x[1]), sorted(ubos, key=lambda x: x[1]))

jobs = [(p, i) for p in PASSES for i in range(1 << len(OPTS))]
res = {}
with cf.ThreadPoolExecutor(os.cpu_count()) as ex:
    for pas, idx, r in ex.map(lambda a: compile_one(*a), jobs):
        res[(pas, idx)] = r

def carr(name, items, ctype):
    if not items: return f"static const {ctype} {name}[1] = {{0}};\n"
    return f"static const {ctype} {name}[] = {{ {', '.join(items)} }};\n"

for pas in PASSES:
    pre = f"g_ffx_fsr2_{pas}_pass"
    o = [f"// generated by gen_fsr2_shaders.py (glslang), do not edit\n#pragma once\n#include <stdint.h>\n",
         f"typedef union ffx_fsr2_{pas}_pass_PermutationKey {{\n    struct {{\n"]
    o += [f"        uint32_t {opt} : 1;\n" for opt in OPTS]
    o.append(f"    }};\n    uint32_t index;\n}} ffx_fsr2_{pas}_pass_PermutationKey;\n\n")
    o.append(f"typedef struct ffx_fsr2_{pas}_pass_PermutationInfo {{\n    const uint32_t blobSize; const unsigned char* blobData;\n"
             "    const uint32_t numStorageImageResources; const char** storageImageResourceNames; const uint32_t* storageImageResourceBindings;\n"
             "    const uint32_t numCombinedSamplerResources; const char** combinedSamplerResourceNames; const uint32_t* combinedSamplerResourceBindings;\n"
             "    const uint32_t numUniformBufferResources; const char** uniformBufferResourceNames; const uint32_t* uniformBufferResourceBindings;\n"
             f"}} ffx_fsr2_{pas}_pass_PermutationInfo;\n\n")
    uniq, table, infos = {}, [], []
    for idx in range(1 << len(OPTS)):
        r = res[(pas, idx)]
        if r is None:                         # e.g. FP16 variant not compilable: fall back to FP32
            r = res[(pas, idx & ~(1 << OPTS.index("FFX_HALF")))]
        if r is None: sys.exit(f"{pas} permutation {idx} failed to compile")
        h = hashlib.sha1(r[0]).hexdigest()
        if h not in uniq:
            k = len(uniq); uniq[h] = k; infos.append(r)
            d, imgs, smps, ubos = r
            o.append(f"static const unsigned char {pre}_blob{k}[] = {{ {','.join(str(b) for b in d)} }};\n")
            for tag, lst in (("img", imgs), ("smp", smps), ("ubo", ubos)):
                o.append(carr(f"{pre}_{tag}names{k}", [f'"{n}"' for n, _ in lst], "char*"))
                o.append(carr(f"{pre}_{tag}binds{k}", [str(b) for _, b in lst], "uint32_t"))
        table.append(uniq[h])
    o.append(f"\nstatic const ffx_fsr2_{pas}_pass_PermutationInfo {pre}_PermutationInfo[] = {{\n")
    for k, (d, imgs, smps, ubos) in enumerate(infos):
        o.append(f"    {{ {len(d)}, {pre}_blob{k}, {len(imgs)}, (const char**){pre}_imgnames{k}, {pre}_imgbinds{k}, "
                 f"{len(smps)}, (const char**){pre}_smpnames{k}, {pre}_smpbinds{k}, "
                 f"{len(ubos)}, (const char**){pre}_ubonames{k}, {pre}_ubobinds{k} }},\n")
    o.append("};\n\n")
    o.append(f"static const int32_t {pre}_IndirectionTable[] = {{ {', '.join(map(str, table))} }};\n")
    open(os.path.join(OUT, f"ffx_fsr2_{pas}_pass_permutations.h"), "w").write("".join(o))
    print(f"{pas}: {len(uniq)} unique blobs")
