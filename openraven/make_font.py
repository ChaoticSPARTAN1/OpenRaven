# Builds ravenui_font.h: ASCII 32..126 as 12x24 8-bit alpha glyphs (DejaVu Sans Mono), baked into the shim.
from PIL import Image, ImageDraw, ImageFont
W, H = 12, 24
f = ImageFont.truetype("/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf", 19)
out = ["// Generated by make_font.py (DejaVu Sans Mono, free license). Do not edit.",
       f"#define FONT_W {W}\n#define FONT_H {H}", "static const unsigned char font_px[95][FONT_H*FONT_W] = {"]
for c in range(32, 127):
    im = Image.new("L", (W, H), 0); d = ImageDraw.Draw(im)
    d.text((0, 1), chr(c), font=f, fill=255)
    out.append("{" + ",".join(str(v) for v in im.tobytes()) + "},")
out.append("};")
open("ravenui_font.h", "w").write("\n".join(out) + "\n")
