#!/bin/bash
# Builds the Vulkan kernels into ravenvk_spv.h (compiled into ravengfx.so; ../build.sh runs this when
# glslc is installed, otherwise it uses the committed header) and the test tools.
set -e
cd "$(dirname "$0")"
glslc -fshader-stage=compute --target-env=vulkan1.3 -O -DACC16=0 conv_cm.comp -o cm_a0.spv
glslc -fshader-stage=compute --target-env=vulkan1.3 -O -DACC16=1 conv_cm.comp -o cm_a1.spv
glslc -fshader-stage=compute --target-env=vulkan1.1 -O conv_plain.comp -o plain.spv
for m in 1 2 3; do glslc -fshader-stage=compute --target-env=vulkan1.1 -O -DMODE=$m misc2.comp -o misc$m.spv; done
python3 - <<'P'
import struct
out = ['// generated by vk/build_vk.sh from conv_cm.comp, conv_plain.comp, misc2.comp - do not edit']
for name, f in (('spv_cm_a0', 'cm_a0.spv'), ('spv_cm_a1', 'cm_a1.spv'), ('spv_plain', 'plain.spv'),
                ('spv_misc1', 'misc1.spv'), ('spv_misc2', 'misc2.spv'), ('spv_misc3', 'misc3.spv')):
    d = open(f, 'rb').read(); w = struct.unpack('<%dI' % (len(d) // 4), d)
    out.append('static const uint32_t %s[%d] = {%s};' % (name, len(w), ','.join('0x%x' % x for x in w)))
open('ravenvk_spv.h', 'w').write('\n'.join(out) + '\n')
P
gcc -O2 -Wall -o vkcheck vkcheck.c ravenvk.c -ldl -lm
echo built
